#include "lemon.h"
#include "spdlog/sinks/stdout_color_sinks.h"
//
#include "base/LemonBase.hpp"
#include "base/LemonBaseApplication.hpp"
#include "base/LemonLog.hpp"
#include "base/LemonPortable.hpp"
#include "spdlog/sinks/daily_file_sink.h"
//
#include <QApplication>
#include <QPixmap>
#include <QSplashScreen>
#include <chrono>

#define LEMON_MODULE_NAME "Main"

void initLogger() {
	auto console_sink = std::make_shared<spdlog::sinks::stdout_color_sink_mt>();
	console_sink->set_level(spdlog::level::warn);
	QDir logDir(Lemon::Portable::logDirectory());
	logDir.mkpath(".");
	// retain last 30 days logs
	auto file_sink = std::make_shared<spdlog::sinks::daily_file_sink_mt>(
	    (logDir.path() + QDir::separator() + "lemonlime-log.txt").toStdString(), 0, 0, false, 30);
	file_sink->set_level(spdlog::level::trace);
	Lemon::base::logger =
	    std::make_shared<spdlog::logger>(spdlog::logger("lemonlime", {console_sink, file_sink}));
	// flush_every() below registers the default logger, so make the application's
	// logger the default one; otherwise the file sink would only be flushed when
	// the process exits normally and a killed process would leave an empty log.
	spdlog::set_default_logger(Lemon::base::logger);
	spdlog::flush_every(std::chrono::seconds(5));
}

int main(int argc, char *argv[]) {

	QCoreApplication::setApplicationName("Lemonlime");

	// The logger has to exist before the application object is constructed:
	// Lemon::LemonApplicationInterface's constructor already logs. The portable
	// layout is decided here as well, because it selects the log directory.
	initLogger();

	Lemon::LemonBaseApplication app(argc, argv);

	// QSettings fixes its format and path when the first QSettings object is
	// created (inside app.Initialize() below), so portable mode has to be
	// configured before that.
	Lemon::Portable::Initialize();

	LOG("portable mode:", Lemon::Portable::isEnabled() ? "enabled" : "disabled");
	LOG("log directory:", Lemon::Portable::logDirectory());

	const auto bundledTools = Lemon::Portable::bundledToolDirectories();

	if (! bundledTools.isEmpty())
		LOG("bundled toolchain:", bundledTools.join(';'));

	app.Initialize();

	if (app.sendMessage("")) {
		app.activeWindow();
		return 0;
	}

#ifdef Q_OS_LINUX
	// fonts.setFamily("Noto Sans CJK SC");
#endif
#ifdef Q_OS_WIN32
	QFont fonts;
	fonts.setFamily("Microsoft YaHei");
	fonts.setHintingPreference(QFont::PreferNoHinting);
	SingleApplication::setFont(fonts);
#endif
#ifdef Q_OS_MAC
	// fonts.setFamily("PingFangSC-Regular");
#endif
	Q_INIT_RESOURCE(resource);
	QPixmap pixmap(":/logo/splash2.png");
	QSplashScreen screen(pixmap.scaled(450, 191, Qt::KeepAspectRatio, Qt::SmoothTransformation));
	LemonLime w;
	qint64 startTime = QDateTime::currentMSecsSinceEpoch();
	int splashTime = w.getSplashTime();

	if (splashTime > 0) {
		screen.show();

		do {
			SingleApplication::processEvents();
		} while (QDateTime::currentMSecsSinceEpoch() - startTime <= splashTime);

		screen.finish(&w);
	}

	w.activateWindow();
	w.show();
	w.welcome();
	return app.exec();
}
